FIRST, LAST = 32, 95


def main():
    data, off, adv, bw = [], [], [], []
    for c in range(FIRST, LAST + 1):
        rows = G.get(chr(c), G["?"])
        assert len(rows) == H and len({len(r) for r in rows}) == 1, chr(c)
        w = len(rows[0])
        off.append(len(data))
        bw.append(w)
        adv.append(w + 1)
        for r in rows:
            px = [15 if ch == "#" else 0 for ch in r] + [0]
            for i in range(0, w, 2):
                data.append(px[i] << 4 | px[i + 1])
    out = ["/* generated by tools/gen_small_font.py: KNOBI-SIX's own 5 x 7 font (hand drawn, GPL-3.0-only), ASCII 32..95 */",
           "#pragma once", "#include <stdint.h>", ""]
    def arr(t, name, v):
        lines = [f"static const {t} {name}[{len(v)}] = {{"]
        for i in range(0, len(v), 24):
            lines.append("    " + ", ".join(str(x) for x in v[i:i + 24]) + ",")
        lines.append("};")
        return lines
    out += arr("uint8_t", "FONT_XS_DATA", data)
    out += arr("uint16_t", "FONT_XS_OFF", off)
    out += arr("uint8_t", "FONT_XS_ADV", adv)
    out += arr("uint8_t", "FONT_XS_BW", bw)
    out.append(f"static const felucca_font_t FONT_XS = {{ {H}, 0, {FIRST}, {LAST}, FONT_XS_ADV, FONT_XS_BW, FONT_XS_OFF, FONT_XS_DATA }};")
    path = Path(__file__).resolve().parent.parent / "firmware/gen/small_font.h"
    path.write_text("\n".join(out) + "\n")
    print(path, len(data), "bytes of glyphs")


if __name__ == "__main__":
    main()
